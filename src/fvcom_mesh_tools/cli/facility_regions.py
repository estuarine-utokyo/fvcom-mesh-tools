"""``fmesh-facility-regions``: a local-refinement recipe from facility polygons.

Each facility (a nori net block, a fish cage, ...) is buffered by its own
length scale times ``--factor``; touching near fields merge; each cluster is
one region at ``--target-h-m`` in a ``recipes/refine`` YAML whose base is an
existing, already refined mesh. The rest of that mesh -- for a nori ground,
the rest of the licensed area -- keeps its size. See
``fvcom_mesh_tools.facility_regions`` and ``docs/local_refine.md`` §6.10.

    fmesh-facility-regions --facilities nets.geojson --target-h-m 5 \\
        --base-mesh case_grd.dat --base-depth case_dep.dat --base-obc case_obc.dat \\
        --ambient-h-m 50 --within licence.geojson --within-where ground=futtsu \\
        --prefix futtsu_nets --out-geojson recipes/refine/futtsu_nets_5m_regions.geojson \\
        --out-recipe recipes/refine/futtsu_nets_5m.yaml
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from fvcom_mesh_tools import facility_regions as fr


def _kv(items):
    out = {}
    for item in items or []:
        if "=" not in item:
            raise SystemExit(f"--where/--within-where expects key=value, got {item!r}")
        k, v = item.split("=", 1)
        out[k] = v
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--facilities", required=True, type=Path, help="GeoJSON of facility polygons")
    ap.add_argument("--where", nargs="*", help="keep features with property key=value")
    ap.add_argument("--id-field", default="id")
    ap.add_argument("--rule", default="long_side", choices=fr.RULES)
    ap.add_argument("--factor", type=float, default=1.0,
                    help="near-field width as a multiple of the facility length (default 1)")
    ap.add_argument("--min-buffer-m", type=float, default=0.0)
    ap.add_argument("--crs", help="metric CRS (default: UTM zone of the facilities)")
    ap.add_argument("--keep-holes", action="store_true",
                    help="do not fill water enclosed by a cluster")
    ap.add_argument("--prefix", default="facilities", help="region name prefix")
    ap.add_argument("--target-h-m", type=float, required=True)
    ap.add_argument("--gradation", type=float, default=0.165)
    ap.add_argument("--dt-expected-s", type=float, default=0.5)
    ap.add_argument("--ambient-h-m", type=float,
                    help="size of the base mesh around the facilities, for the report")
    ap.add_argument("--within", type=Path, help="polygon to report against (e.g. the licence)")
    ap.add_argument("--within-where", nargs="*")
    ap.add_argument("--base-mesh", required=True, type=Path)
    ap.add_argument("--base-depth", type=Path)
    ap.add_argument("--base-obc", type=Path)
    ap.add_argument("--out-geojson", required=True, type=Path)
    ap.add_argument("--out-recipe", required=True, type=Path)
    ap.add_argument("--out-report", type=Path, help="JSON report (default: next to the recipe)")
    a = ap.parse_args(argv)

    for p in (a.facilities, a.base_mesh, a.base_depth, a.base_obc, a.within):
        if p is not None and not p.exists():
            raise SystemExit(f"not found: {p}")
    facilities = fr.read_facilities(a.facilities, _kv(a.where), a.id_field)
    regions, facs, crs = fr.facility_regions(
        facilities, factor=a.factor, rule=a.rule, min_buffer_m=a.min_buffer_m, crs=a.crs,
        fill_holes=not a.keep_holes, prefix=a.prefix)
    within_m = None
    if a.within is not None:
        import pyproj
        from shapely.ops import transform, unary_union

        fwd = pyproj.Transformer.from_crs("EPSG:4326", crs, always_xy=True).transform
        within = fr.read_facilities(a.within, _kv(a.within_where), None)
        within_m = unary_union([transform(fwd, p) for _, p in within])
    rep = fr.summary(regions, facs, target_h_m=a.target_h_m, ambient_h_m=a.ambient_h_m,
                     gradation=a.gradation, within_m=within_m)
    meta = {"tool": "fmesh-facility-regions", "argv": sys.argv[1:] if argv is None else argv,
            "facilities": str(a.facilities.resolve()), "where": _kv(a.where), "rule": a.rule,
            "factor": a.factor, "min_buffer_m": a.min_buffer_m, "metric_crs": crs}
    rep["inputs"] = meta
    rep["per_facility"] = [{"id": str(f.fid), "length_m": round(f.length_m, 2),
                            "buffer_m": round(f.buffer_m, 2)} for f in facs]

    a.out_geojson.parent.mkdir(parents=True, exist_ok=True)
    a.out_recipe.parent.mkdir(parents=True, exist_ok=True)
    fr.write_regions_geojson(a.out_geojson, regions, crs, meta)
    header = (f"Generated by fmesh-facility-regions from {a.facilities.name}: each facility\n"
              f"buffered by {a.factor:g} x its {a.rule} length, touching near fields merged,\n"
              f"{len(facs)} facilities -> {len(regions)} regions at {a.target_h_m:g} m.\n"
              "Regenerate rather than edit; the report is beside this file.")
    a.out_recipe.write_text(fr.recipe_text(
        a.out_recipe, a.out_geojson, regions, base_mesh=a.base_mesh, base_depth=a.base_depth,
        base_obc=a.base_obc, target_h_m=a.target_h_m, gradation=a.gradation,
        dt_expected_s=a.dt_expected_s, header=header))
    out_report = a.out_report or a.out_recipe.with_suffix(".report.json")
    out_report.write_text(json.dumps(rep, indent=1) + "\n")
    print(json.dumps({k: v for k, v in rep.items()
                      if k not in ("per_region", "per_facility", "inputs")}, indent=1))
    print(f"wrote {a.out_geojson}\nwrote {a.out_recipe}\nwrote {out_report}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
